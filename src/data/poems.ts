export interface JieYue {
  marriage: string;     // 感情姻緣
  wealth: string;       // 財運
  career: string;       // 事業
  health: string;       // 健康
  study: string;        // 學業
  travel: string;       // 出行
  general: string;      // 綜合
}

export interface Poem {
  id: number;              // 1-64
  number: number;          // 籤號
  hexagramName: string;    // 卦名
  hexagramNumber: number;  // 卦序
  level: string;           // 吉凶等級
  title: string;           // 籤題
  content: string;         // 七言絕句 (4行×7字)
  vernacular: string;      // 白話解釋
  story: string;           // 典故說明
  jieYue: JieYue;
}

// Helper to create poem objects concisely
function p(
  id: number, hexName: string, hexNum: number, level: string,
  title: string, content: string, vernacular: string, story: string,
  marriage: string, wealth: string, career: string,
  health: string, study: string, travel: string, general: string,
): Poem {
  return { id, number: id, hexagramName: hexName, hexagramNumber: hexNum, level, title, content, vernacular, story, jieYue: { marriage, wealth, career, health, study, travel, general } };
}

