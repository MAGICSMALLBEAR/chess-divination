export function getPoemById(id: number): Poem {
  const poem = ALL_POEMS.find(p => p.id === id);
  if (!poem) {
    // Fallback: return poem #1
    return ALL_POEMS[0];
  }
  return poem;
}

export function getPoemsByLevel(level: string): Poem[] {
  return ALL_POEMS.filter(p => p.level === level);
}

export function getPoemsByHexagram(hexNum: number): Poem[] {
  return ALL_POEMS.filter(p => p.hexagramNumber === hexNum);
}

